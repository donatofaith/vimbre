/** Resolve legacy workspace color declarations to the shared dark palette.
 * Layout, images, dimensions, animation and the light theme are untouched.
 * Regenerate after editing a workspace stylesheet. */
import fs from 'node:fs'
import path from 'node:path'
import postcss from 'postcss'
const prefix='html[data-workspace-theme=dark] '
const files=['src/styles/global.css','src/styles/polish.css','src/styles/action-colours.css',...fs.readdirSync('src/app/layouts').filter(f=>f.endsWith('.css')).map(f=>'src/app/layouts/'+f)]
function collect(dir){for(const e of fs.readdirSync(dir,{withFileTypes:true})){const p=path.join(dir,e.name);if(e.isDirectory()&&!['public','appearance','auth','analytics'].includes(e.name))collect(p);else if(e.isFile()&&p.endsWith('.css'))files.push(p)}}
collect('src/features')
function rgba(hex){let v=hex.slice(1);if(v.length===3||v.length===4)v=v.split('').map(c=>c+c).join('');return [parseInt(v.slice(0,2),16),parseInt(v.slice(2,4),16),parseInt(v.slice(4,6),16),v.length===8?parseInt(v.slice(6),16)/255:1]}
function color([r,g,b,a=1],kind){
 const hi=Math.max(r,g,b),lo=Math.min(r,g,b),avg=(r+g+b)/3
 if(kind==='background'){
  if(a<.3)return null // Deliberate glass highlights and transparent overlays.
  if(lo>175){if(hi-lo<38)return avg>246?'var(--surface)':'var(--surface-raised)';if(b>r+12)return 'var(--blue-soft)';if(g>b+10&&g>r-15)return 'var(--theme-success-surface)';if(r>b+20&&g>b+10)return 'var(--theme-warning-surface)';return 'var(--theme-danger-surface)'}
  if(avg>145&&hi-lo<40)return 'var(--border)'
  return null // Preserve saturated actions and deliberate brand banners.
 }
 if(kind==='border'){
  if(a<.3)return null
  if(avg>135)return hi-lo<50?'var(--border)':b>r+15?'var(--blue-soft)':r>b+30?'var(--theme-warning-surface)':'var(--border)'
  return null
 }
 if(kind==='text'){
  if(lo>228)return null // On-brand/on-accent white remains white.
  if(hi-lo<35)return avg>100?'var(--muted)':'var(--text)'
  if(b>r+35&&b>g+15&&b>140)return 'var(--blue)'
  if(r>g*1.4&&r>b*1.3)return 'var(--error)'
  if(g>r*1.35&&g>b*1.1)return 'var(--success)'
  if(r>b*1.25&&g>b*1.1)return 'var(--warning)'
  return avg>120?'var(--muted)':'var(--text)'
 }
 return null
}
function transform(d){
 const prop=d.prop.toLowerCase();let kind
 if(['color','fill','stroke','caret-color','text-decoration-color'].includes(prop))kind='text'
 else if(prop==='background'||prop==='background-color'||prop==='background-image')kind='background'
 else if(prop.startsWith('border')||prop==='outline'||prop==='outline-color')kind='border'
 else return null
 let value=d.value
 if(kind==='background')value=value.replace(/var\(--navy\)/g,'var(--brand-navy)').replace(/var\(--blue(?:-hover)?\)/g,'var(--action-blue)')
 if(kind==='text')value=value.replace(/var\(--surface\)/g,'var(--on-accent)').replace(/var\(--navy-secondary\)/g,'var(--text)')
 value=value.replace(/#[\da-f]{3,8}\b/gi,h=>color(rgba(h),kind)||h)
 value=value.replace(/\bwhite\b/g,kind==='background'?'var(--surface)':'white')
 value=value.replace(/\bblack\b/g,kind==='text'?'var(--text)':'black')
 // Opaque and translucent neutral RGB fills used by glass surfaces.
 value=value.replace(/rgba?\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)(?:\s*[,/]\s*([\d.]+)(%)?)?\s*\)/g,(raw,r,g,b,a,percent)=>color([+r,+g,+b,a===undefined?1:+a/(percent?100:1)],kind)||raw)
 return value!==d.value?value:null
}
const output=postcss.root()
for(const file of files){const root=postcss.parse(fs.readFileSync(file,'utf8'));function visit(container,dest){for(const n of container.nodes||[]){if(n.type==='atrule'&&['media','supports','container','layer'].includes(n.name)){const at=postcss.atRule({name:n.name,params:n.params});visit(n,at);if(at.nodes?.length)dest.append(at)}else if(n.type==='rule'){
 // Preserve the existing navy sidebar and explicit public presentation.
 const selectors=n.selectors.filter(s=>!/(?:\.rs-|\.public-|\.landing-|\.sidebar\b|\.vw-sidebar\b|\.vw-navigation\b|\.vw-account\b|\.vw-utilities\b|:root|^html|^body)/.test(s))
 if(!selectors.length)continue
 const rule=postcss.rule({selector:selectors.map(s=>prefix+s).join(',')})
 for(const d of n.nodes){if(d.type!=='decl')continue;const value=transform(d);if(value)rule.append(postcss.decl({prop:d.prop,value,important:d.important}))}
 if(rule.nodes.length)dest.append(rule)
 }}}visit(root,output)}
fs.writeFileSync('src/features/appearance/workspace-theme.generated.css','/* Generated by scripts/build-workspace-theme.mjs; semantic color overrides only. */\n'+output.toString()+'\n')
console.log(`Prepared dark color coverage from ${files.length} workspace stylesheets.`)
